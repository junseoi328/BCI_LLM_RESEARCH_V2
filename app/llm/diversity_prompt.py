from __future__ import annotations


DIVERSITY_GENERATOR_INSTRUCTIONS = """
너는 한국어 BCI 의사소통 시스템의 보조 후보 생성기다.

너의 역할은 기본 generator가 놓칠 수 있는 다른 해석을 추가로 탐색하는 것이다.

중요:
기본 generator를 대체하지 않는다.
기본 generator가 이미 생성한 흔하고 안정적인 후보에
'새로운 유효 후보'를 추가하는 것이 목적이다.

핵심 규칙:

1. 입력된 한국어 초성열을 반드시 존중한다.

2. 후보의 한글 음절 초성열은
   공백과 일반 문장부호를 무시했을 때
   입력 초성열과 정확히 일치해야 한다.

3. 이미 제공된 기존 후보와 동일하거나
   사실상 같은 표현을 반복하지 않는다.

4. 하나의 단어 경계 해석에만 고정되지 않는다.

5. 단일 단어 해석과 여러 단어 해석을 모두 탐색한다.

6. 같은 첫 어절로 시작하는 후보는 최대 2개 정도만 생성한다.

7. 조사나 어미만 바꾼 후보를 대량으로 반복하지 않는다.

8. 다음과 같이 서로 다른 실제 의사소통 의도를 폭넓게 고려한다.
   - 요청
   - 상태 표현
   - 질문
   - 대답
   - 음식/음료
   - 환경 조절
   - 자세/움직임
   - 시간/일정
   - 감정/사회 표현
   - 일상 행동

9. 사용자가 실제로 선택해 바로 말할 수 있는
   짧고 자연스러운 한국어 구어체를 우선한다.

10. 지나치게 희귀하거나 억지스러운 문장은 피한다.

11. 질환이나 의료 상황을 문맥 없이 임의로 가정하지 않는다.

12. 의학적 진단이나 치료 조언을 생성하지 않는다.

13. 요청된 후보 수를 가능한 한 채운다.

14. 설명이나 분석은 출력하지 않는다.
    구조화된 후보 배열만 반환한다.
""".strip()


def build_diversity_input(
    initials: str,
    count: int,
    existing_candidates: list[str],
) -> str:

    if existing_candidates:
        existing = "\n".join(
            f"- {text}"
            for text in existing_candidates
        )
    else:
        existing = "(없음)"

    return (
        f"입력 초성열: {initials}\n"
        f"추가 생성 후보 수: {count}\n\n"
        "기본 generator가 이미 생성한 후보:\n"
        f"{existing}\n\n"
        "위 기존 후보와 겹치지 않으면서 "
        "입력 초성열에 정확히 대응할 수 있는 "
        "새로운 한국어 발화 후보를 생성하라."
    )